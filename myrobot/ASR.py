STATUS_FIRST_FRAME = 0  # first frame flag
STATUS_CONTINUE_FRAME = 1  # middle frame flag
STATUS_LAST_FRAME = 2  # last frame flag

wsParam = None
gResult = ''


class Ws_Param(object):
    # initialize
    def __init__(self, APPID, APIKey, APISecret, AudioFile):
        self.APPID = APPID
        self.APIKey = APIKey
        self.APISecret = APISecret
        self.AudioFile = AudioFile

        # common parameters
        self.CommonArgs = {"app_id": self.APPID}
        # business parameters (more customization options available on the official website)
        self.BusinessArgs = {"domain": "iat", "language": "zh_cn", "accent": "mandarin", "vinfo": 1, "vad_eos": 10000}

    # generate url
    def create_url(self):
        url = 'wss://ws-api.xfyun.cn/v2/iat'
        # generate RFC1123 timestamp
        now = datetime.now()
        date = format_date_time(mktime(now.timetuple()))

        # concatenate string
        signature_origin = "host: " + "ws-api.xfyun.cn" + "\n"
        signature_origin += "date: " + date + "\n"
        signature_origin += "GET " + "/v2/iat " + "HTTP/1.1"
        # hmac-sha256 encryption
        signature_sha = hmac.new(self.APISecret.encode('utf-8'), signature_origin.encode('utf-8'),
                                 digestmod=hashlib.sha256).digest()
        signature_sha = base64.b64encode(signature_sha).decode(encoding='utf-8')

        authorization_origin = "api_key=\"%s\", algorithm=\"%s\", headers=\"%s\", signature=\"%s\"" % (
            self.APIKey, "hmac-sha256", "host date request-line", signature_sha)
        authorization = base64.b64encode(authorization_origin.encode('utf-8')).decode(encoding='utf-8')
        # combine auth params into dict
        v = {
            "authorization": authorization,
            "date": date,
            "host": "ws-api.xfyun.cn"
        }
        # concatenate auth params, generate url
        url = url + '?' + urlencode(v)
        # print("date: ",date)
        # print("v: ",v)
        # This prints the connection URL. When referencing this demo, uncomment the above print to compare if the url generated by your code matches
        # print('websocket url :', url)
        return url


# handle websocket message
def on_message(ws, message):
    global gResult
    try:
        code = json.loads(message)["code"]
        sid = json.loads(message)["sid"]
        if code != 0:
            errMsg = json.loads(message)["message"]

        else:
            data = json.loads(message)["data"]["result"]["ws"]
            # print(json.loads(message))
            result = ""
            for i in data:
                for w in i["cw"]:
                    result += w["w"]
            gResult = gResult + result
    except Exception as e:
        print("receive msg,but parse exception:", e)


# handle websocket error
def on_error(ws, error):
    print("### error:", error)


# handle websocket close
def on_close(ws):
    pass


# handle websocket connection open
def on_open(ws):
    global wsParam

    def run(*args):
        frameSize = 8000  # audio frame size
        intervel = 0.04  # send interval (unit: s)
        status = STATUS_FIRST_FRAME  # audio status: first/middle/last frame

        with open(wsParam.AudioFile, "rb") as fp:
            while True:
                buf = fp.read(frameSize)
                # end of file
                if not buf:
                    status = STATUS_LAST_FRAME
                # first frame: send with business params
                # appid must be included, only needed in first frame
                if status == STATUS_FIRST_FRAME:

                    d = {"common": wsParam.CommonArgs,
                         "business": wsParam.BusinessArgs,
                         "data": {"status": 0, "format": "audio/L16;rate=16000",
                                  "audio": str(base64.b64encode(buf), 'utf-8'),
                                  "encoding": "raw"}}
                    d = json.dumps(d)
                    ws.send(d)
                    status = STATUS_CONTINUE_FRAME
                # middle frame
                elif status == STATUS_CONTINUE_FRAME:
                    d = {"data": {"status": 1, "format": "audio/L16;rate=16000",
                                  "audio": str(base64.b64encode(buf), 'utf-8'),
                                  "encoding": "raw"}}
                    ws.send(json.dumps(d))
                # last frame
                elif status == STATUS_LAST_FRAME:
                    d = {"data": {"status": 2, "format": "audio/L16;rate=16000",
                                  "audio": str(base64.b64encode(buf), 'utf-8'),
                                  "encoding": "raw"}}
                    ws.send(json.dumps(d))
                    time.sleep(1)
                    break
                # simulate audio sampling interval
                time.sleep(intervel)
        ws.close()

    thread.start_new_thread(run, ())


